export async function POST(req: NextRequest) {
  const { error } = await requireRole(COMMITTEE_ROLES)
  if (error) return error

  let inserted = 0
  for (const tpl of SEED_TEMPLATES) {
    const existing = await sql`
      SELECT id FROM letter_templates WHERE title = ${tpl.title} LIMIT 1
    `
    if (existing.length === 0) {
      await sql`
        INSERT INTO letter_templates (category, title, subject, body)
        VALUES (${tpl.category}, ${tpl.title}, ${tpl.subject}, ${tpl.body})
      `
      inserted++
    }
  }
  return jsonOK({ inserted, total: SEED_TEMPLATES.length })
}
